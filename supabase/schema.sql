create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null unique,
  alt_phone text,
  address text,
  landmark text,
  floor_apt text,
  area text,
  pincode text,
  latitude numeric,
  longitude numeric,
  customer_type text not null default 'regular',
  delivery_notes text,
  credit_limit numeric(12, 2) not null default 0,
  total_orders integer not null default 0,
  total_spent numeric(12, 2) not null default 0,
  outstanding_balance numeric(12, 2) not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  token_number text,
  customer_id bigint not null references public.customers(id) on delete restrict,
  status text not null,
  source text not null default 'walkin',
  order_date date not null default current_date,
  pickup_date date,
  expected_delivery_date date,
  actual_delivery_date date,
  pickup_slot text,
  delivery_slot text,
  subtotal numeric(12, 2) not null default 0,
  discount_percent numeric(5, 2) not null default 0,
  discount_amount numeric(12, 2) not null default 0,
  delivery_charge numeric(12, 2) not null default 0,
  express_charge numeric(12, 2) not null default 0,
  gst_percent numeric(5, 2) not null default 0,
  gst_amount numeric(12, 2) not null default 0,
  total_amount numeric(12, 2) not null default 0,
  amount_paid numeric(12, 2) not null default 0,
  amount_due numeric(12, 2) not null default 0,
  payment_status text not null default 'unpaid',
  payment_mode text,
  is_express boolean not null default false,
  is_doorstep boolean not null default true,
  weight_kg numeric(10, 3),
  notes text,
  staff_notes text,
  pickup_address text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  service_type text not null,
  item_name text not null,
  category text,
  quantity integer not null default 1,
  weight_kg numeric(10, 3),
  price_per_unit numeric(12, 2) not null default 0,
  subtotal numeric(12, 2) not null default 0,
  notes text
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  amount numeric(12, 2) not null,
  mode text not null,
  reference text,
  received_by text,
  notes text,
  received_at timestamptz not null default now()
);

create table if not exists public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  from_status text,
  to_status text not null,
  changed_by text,
  notes text,
  changed_at timestamptz not null default now()
);

create table if not exists public.prices (
  id bigint generated by default as identity primary key,
  service_type text not null,
  item_name text not null,
  category text not null default 'clothing',
  price numeric(12, 2) not null default 0,
  price_per_kg numeric(12, 2),
  is_per_kg boolean not null default false,
  minimum_kg numeric(10, 3),
  active boolean not null default true
);

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  date date not null default current_date,
  category text not null,
  description text,
  amount numeric(12, 2) not null,
  payment_mode text not null default 'cash',
  reference text,
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  key text primary key,
  value text not null
);

alter table public.prices add column if not exists minimum_kg numeric(10, 3);

